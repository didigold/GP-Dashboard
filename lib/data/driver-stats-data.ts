export interface RoundPerformance {
  round: number;
  circuitName: string;
  country: string;
  gridPos: number;
  sprintPos: number; // 0 for DNF/DNS
  sundayPos: number; // 0 for DNF/DNS
  delta: number; // gridPos - sundayPos (>0 means gained places)
  points: number;
  status: 'Win' | 'Podium' | 'Top 10' | 'Points' | 'No Points' | 'DNF';
}

