export function getRiderByNumber(num: number | string): GridRider | undefined {
  const n = typeof num === 'string' ? parseInt(num, 10) : num;
  return MOTOGP_RIDERS.find((r) => r.number === n);
}

export function getRiderBySlug(slug: string): GridRider | undefined {
  return MOTOGP_RIDERS.find((r) => r.slug === slug || r.id === slug);
}

export function getTeamBySlug(slug: string): GridTeam | undefined {
  return MOTOGP_TEAMS.find((t) => t.slug === slug || t.id === slug);
}

export function getTeamRiders(teamId: string): GridRider[] {
  return MOTOGP_RIDERS.filter((r) => r.team_id === teamId);
}
